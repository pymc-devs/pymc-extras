"""
Model Equivalence

Full-stack integration suite: a recorded L-BFGS trajectory is replayed through
LBFGSStreamingCallback (which computes alpha, s, z internally, exactly as scipy.minimize
would), and the resulting ELBO must be statistically equivalent to the recorded reference.

Fixture files live in tests/inference/pathfinder/fixtures/ and are generated by running:

    python tests/inference/pathfinder/generate_fixtures.py

Each .npz file contains:
    x_full     – position history  (L+1, N)
    g_full     – gradient history  (L+1, N)
    elbo_ref   – reference ELBO    (L,)
"""

import os

from unittest.mock import MagicMock, patch

import numpy as np
import pymc as pm
import pytest

from pymc.blocking import DictToArrayBijection
from pytensor.tensor.optimize import LRUCache1

from pymc_extras.inference.pathfinder.bfgs_sample import (
    get_neg_logp_dlogp_of_ravel_inputs,
    make_pathfinder_sample_fn,
)
from pymc_extras.inference.pathfinder.lbfgs import LBFGSStatus, LBFGSStreamingCallback
from pymc_extras.inference.pathfinder.results import FAILED_PATH_STATUS
from tests.inference.pathfinder.conftest import (
    MAXCOR,
    NUM_DRAWS,
    NUM_ELBO_DRAWS,
    make_single_fn,
    run_streaming_lbfgs,
)
from tests.inference.pathfinder.equivalence_models import MODEL_FACTORIES, make_ard_regression

# Must stay in sync with generate_fixtures.py
FIXTURES_DIR = os.path.join(os.path.dirname(__file__), "fixtures")
ELBO_SEED = 12345
REPLAY_EPSILON = 1e-12

ALL_MODEL_NAMES = list(MODEL_FACTORIES.keys())


